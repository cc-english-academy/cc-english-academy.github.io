-- NEW: every time a student opens a book we log it → streaks + leaderboard.
-- material_id gets the same type as materials.id (uuid or bigint, depending
-- on how the materials table was originally created).
do $$
declare v_type text;
begin
  select format_type(a.atttypid, a.atttypmod) into v_type
    from pg_attribute a
   where a.attrelid = 'public.materials'::regclass and a.attname = 'id';
  execute format($f$
    create table if not exists public.material_reads (
      id           bigint generated by default as identity primary key,
      student_id   uuid not null references public.profiles(id) on delete cascade,
      material_id  %s not null references public.materials(id) on delete cascade,
      club         text,
      read_on      date not null default current_date,
      created_at   timestamptz not null default now(),
      unique (student_id, material_id, read_on)
    )$f$, v_type);
end $$;


-- ----- live sessions: book a seat (checks club, time, capacity and an active plan) -----
create or replace function public.book_session(p_session text)
returns void language plpgsql security definer set search_path = public as $$
declare s public.sessions%rowtype;
begin
  if auth.uid() is null then raise exception 'Please sign in first'; end if;
  if public.my_role() <> 'student' then raise exception 'Only student accounts can book a seat'; end if;
  select * into s from public.sessions where id::text = p_session for update;
  if not found then raise exception 'This session no longer exists'; end if;
  if s.club is distinct from public.my_club() then raise exception 'This session is for another club'; end if;
  if s.starts_at <= now() then raise exception 'This session has already started'; end if;
  if exists (select 1 from public.bookings where session_id = s.id and student_id = auth.uid()) then return; end if;
  if not exists (select 1 from public.enrollments e where e.student_id = auth.uid() and e.status = 'active'
                   and (e.ends_at is null or e.ends_at > now())) then
    raise exception 'You need an active plan to book a seat — choose a plan first';
  end if;
  if (select count(*) from public.bookings where session_id = s.id) >= s.capacity then
    raise exception 'This session is full';
  end if;
  if exists (select 1 from public.bookings b join public.sessions o on o.id = b.session_id
              where b.student_id = auth.uid() and o.id <> s.id
                and o.starts_at < s.starts_at + make_interval(mins => s.duration_min)
                and s.starts_at < o.starts_at + make_interval(mins => o.duration_min)) then
    raise exception 'You already have a class booked at this time';
  end if;
  insert into public.bookings (session_id, student_id) values (s.id, auth.uid());
end $$;


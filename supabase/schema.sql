-- Exam questions for a student, options shuffled, correct answer hidden.
drop function if exists public.get_exam(text, text);
create or replace function public.get_exam(p_club text, p_level text)
returns table (id text, question text, options text[])
language sql volatile security definer set search_path = public as $$
  select q.id::text, q.question,
         (select array_agg(o order by random())
            from unnest(array[q.option_a, q.option_b, q.option_c, q.option_d]) as o)
    from public.exam_questions q
   where q.club = p_club and q.level = p_level
     and (public.is_teacher() or p_club = public.my_club())
   order by q.created_at;
$$;

-- Grades the exam on the server and records the attempt.
-- p_answers = {"<question id>": "<chosen option text>", ...}
create or replace function public.submit_exam(p_club text, p_level text, p_answers jsonb)
returns table (score int, passed boolean, correct int, total int)
language plpgsql security definer set search_path = public as $$
declare
  v_total int; v_correct int; v_score int; v_passed boolean;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if p_club is distinct from public.my_club() then raise exception 'This exam is not for your club'; end if;

  select count(*), count(*) filter (where p_answers->>(q.id::text) = q.option_a)
    into v_total, v_correct
    from public.exam_questions q
   where q.club = p_club and q.level = p_level;

  if v_total = 0 then raise exception 'No questions for this level yet'; end if;

  v_score  := round(v_correct * 100.0 / v_total);
  v_passed := v_score >= 70;

  insert into public.exam_attempts (student_id, club, level, score, passed)
  values (auth.uid(), p_club, p_level, v_score, v_passed);

  return query select v_score, v_passed, v_correct, v_total;
end $$;


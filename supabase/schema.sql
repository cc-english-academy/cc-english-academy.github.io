do $$
declare v_sess text; v_asg text;
begin
  select format_type(a.atttypid, a.atttypmod) into v_sess from pg_attribute a
   where a.attrelid = 'public.sessions'::regclass and a.attname = 'id';
  select format_type(a.atttypid, a.atttypmod) into v_asg from pg_attribute a
   where a.attrelid = 'public.assignments'::regclass and a.attname = 'id';

  -- the Zoom link is kept apart so students only see it after booking a seat
  execute format($f$
    create table if not exists public.session_links (
      session_id  %s primary key references public.sessions(id) on delete cascade,
      zoom_url    text not null
    )$f$, v_sess);

  execute format($f$
    create table if not exists public.bookings (
      id          bigint generated by default as identity primary key,
      session_id  %s not null references public.sessions(id) on delete cascade,
      student_id  uuid not null default auth.uid() references public.profiles(id) on delete cascade,
      attendance  text check (attendance in ('present','absent')),
      created_at  timestamptz not null default now(),
      unique (session_id, student_id)
    )$f$, v_sess);

  execute format($f$
    create table if not exists public.submissions (
      id             bigint generated by default as identity primary key,
      assignment_id  %s not null references public.assignments(id) on delete cascade,
      student_id     uuid not null default auth.uid() references public.profiles(id) on delete cascade,
      answer         text not null,
      grade          int check (grade between 0 and 100),
      feedback       text,
      graded_at      timestamptz,
      created_at     timestamptz not null default now(),
      unique (assignment_id, student_id)
    )$f$, v_asg);
end $$;

  if not public.is_teacher() then raise exception 'Not allowed'; end if;
  select jsonb_build_object(
    'students',        (select count(*) from public.profiles where role = 'student'),
    'active_students', (select count(distinct student_id) from public.enrollments where status = 'active' and (ends_at is null or ends_at > now())),
    'pending',         (select count(*) from public.enrollments where status = 'pending'),
    'revenue_month',   (select coalesce(sum(amount), 0) from public.enrollments where status in ('active','stopped') and activated_at >= date_trunc('month', now())),
    'classes_week',    (select count(*) from public.sessions where starts_at >= now() and starts_at < now() + interval '7 days'),
    'attendance_30d',  (select case when count(*) filter (where b.attendance is not null) = 0 then null
                               else round(100.0 * count(*) filter (where b.attendance = 'present') / count(*) filter (where b.attendance is not null)) end
                          from public.bookings b join public.sessions s on s.id = b.session_id
                         where s.starts_at > now() - interval '30 days' and s.starts_at < now()),
    'to_grade',        (select count(*) from public.submissions where grade is null),
    'teacher_requests',(select count(*) from public.profiles where teacher_request and role = 'student'),
    'expiring', coalesce((select jsonb_agg(x order by x->>'ends_at') from (
        select jsonb_build_object('name', p.full_name, 'club', p.club, 'plan', e.plan, 'ends_at', e.ends_at) x
          from public.enrollments e join public.profiles p on p.id = e.student_id
         where e.status = 'active' and e.ends_at between now() and now() + interval '10 days' limit 20) q), '[]'::jsonb),
    'low_credit', coalesce((select jsonb_agg(x) from (
        select jsonb_build_object('name', p.full_name, 'club', p.club, 'left', (public.plan_status(p.id)->>'left')::int) x
          from public.profiles p
         where p.role = 'student' and (public.plan_status(p.id)->>'left')::int <= 1 limit 20) q), '[]'::jsonb)
  ) into v;
  return v;
end $$;

drop function if exists public.request_enrollment(text, text);
-- returns the request's id (a bank transfer attaches its receipt to it)
create or replace function public.request_enrollment(p_plan text, p_method text)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_price numeric; v_id bigint;
begin
  if auth.uid() is null then raise exception 'Please sign in first'; end if;
  if public.my_role() <> 'student' then raise exception 'Plans are for student accounts'; end if;
  v_price := public.plan_price(p_plan);
  if v_price is null then raise exception 'Unknown plan'; end if;
  if p_method not in ('tamara','visa','whatsapp','bank') then raise exception 'Unknown payment method'; end if;
  update public.enrollments set method = p_method, amount = v_price
   where student_id = auth.uid() and plan = p_plan and status = 'pending'
  returning id into v_id;
  if v_id is null then
    insert into public.enrollments (student_id, plan, method, amount, status)
    values (auth.uid(), p_plan, p_method, v_price, 'pending') returning id into v_id;
  end if;
  return v_id;
end $$;

-- a student attaches the bank-transfer receipt to their own waiting request
create or replace function public.attach_receipt(p_enrollment bigint, p_path text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or p_path is null or split_part(p_path, '/', 1) <> auth.uid()::text then raise exception 'Not allowed'; end if;
  update public.enrollments set receipt_path = p_path, method = 'bank'
   where id = p_enrollment and student_id = auth.uid() and status = 'pending';
  if not found then raise exception 'This request is no longer waiting for payment'; end if;
end $$;
grant execute on function public.attach_receipt(bigint, text) to authenticated;

-- ----- Instagram: the admin saves the token from the dashboard and sees the sync status -----
create or replace function public.set_instagram_token(p_token text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Only an admin can connect Instagram'; end if;
  if p_token is null or length(trim(p_token)) < 30 then raise exception 'This does not look like an Instagram access token'; end if;
  insert into public.app_secrets (key, value, updated_at) values ('instagram_token', trim(p_token), now())
  on conflict (key) do update set value = excluded.value, updated_at = now();
  delete from public.app_secrets where key = 'instagram_status';
end $$;

create or replace function public.instagram_status()
returns jsonb language sql stable security definer set search_path = public as $$
  select case when not public.is_admin() then null else jsonb_build_object(
    'connected',        exists (select 1 from public.app_secrets where key = 'instagram_token'),
    'token_updated_at', (select updated_at from public.app_secrets where key = 'instagram_token'),
    'status',           (select value::jsonb from public.app_secrets where key = 'instagram_status'),
    'videos',           (select count(*) from public.instagram_posts)) end;
$$;

